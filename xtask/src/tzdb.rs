//! The tzdb zones the server counts in (CM-64): `conformance/tzdb/zoneinfo` holds every zone of the pinned IANA release named in `conformance/tzdb/version` as `TZif` compiled by `zic -b slim` from that release's data, one `<name>.tzif` file per zone name; `cargo xtask tzdb` writes `crates/query/src/domain/tzdb/zones.rs`, the name table that embeds them with zones of identical bytes sharing one file, and the `generated` check regenerates it and compares byte for byte.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::Violation;

/// The vendored zones.
pub(crate) const ZONEINFO: &str = "conformance/tzdb/zoneinfo";

/// The vendored release.
pub(crate) const VERSION: &str = "conformance/tzdb/version";

/// The generated name table.
pub(crate) const OUT: &str = "crates/query/src/domain/tzdb/zones.rs";

/// How the generated table reaches the repository root.
const UP: &str = "../../../../../";

const SUFFIX: &str = ".tzif";

fn zones(root: &Path, dir: &Path, out: &mut BTreeMap<String, Vec<u8>>) -> Result<(), String> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| format!("{}: {e}", dir.display()))?.path();
        if path.is_dir() {
            zones(root, &path, out)?;
            continue;
        }
        let rel = path
            .strip_prefix(root.join(ZONEINFO))
            .map_err(|e| format!("{}: {e}", path.display()))?
            .to_string_lossy()
            .replace('\\', "/");
        let name = rel
            .strip_suffix(SUFFIX)
            .ok_or_else(|| format!("{rel}: not a {SUFFIX} file"))?
            .to_owned();
        let bytes = std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        if !bytes.starts_with(b"TZif") {
            return Err(format!("{rel}: not TZif"));
        }
        out.insert(name, bytes);
    }
    Ok(())
}

/// The name table for the zones under `root`.
pub(crate) fn render(root: &Path) -> Result<String, String> {
    let version_path = root.join(VERSION);
    let version = std::fs::read_to_string(&version_path)
        .map_err(|e| format!("{}: {e}", version_path.display()))?
        .trim()
        .to_owned();
    if version.len() != 5 || !version.bytes().take(4).all(|b| b.is_ascii_digit()) {
        return Err(format!("{VERSION}: release {version:?}"));
    }
    let mut found: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    zones(root, &root.join(ZONEINFO), &mut found)?;
    if found.is_empty() {
        return Err("no zones".to_owned());
    }
    let mut first: BTreeMap<String, String> = BTreeMap::new();
    let mut out = format!(
        "//! The zones of tzdb {version}, generated by `cargo xtask tzdb` from `{ZONEINFO}` (CM-64).\n\n/// The tzdb release of the zones.\npub(crate) const VERSION: &str = \"{version}\";\n\n/// Every zone name with its `TZif` bytes, in ascending name order.\n#[rustfmt::skip]\npub(crate) const ZONES: &[(&str, &[u8])] = &[\n"
    );
    for (name, bytes) in &found {
        let digest = crate::sha256::hex_digest(bytes);
        let file = first.entry(digest).or_insert_with(|| name.clone());
        let _ = writeln!(
            out,
            "    (\"{name}\", include_bytes!(\"{UP}{ZONEINFO}/{file}{SUFFIX}\")),"
        );
    }
    out.push_str("];\n");
    Ok(out)
}

/// `cargo xtask tzdb`: writes the name table.
pub(crate) fn write(root: &Path) -> Result<(), String> {
    let text = render(root)?;
    let path = root.join(OUT);
    std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// The committed name table when it differs from a fresh generation (T-41 rule 4).
pub(crate) fn check(root: &Path) -> Result<Vec<Violation>, String> {
    let want = render(root)?;
    let have = std::fs::read_to_string(root.join(OUT)).unwrap_or_default();
    Ok(if have == want {
        Vec::new()
    } else {
        vec![Violation {
            rule: "generated",
            path: PathBuf::from(OUT),
            message: "differs from the vendored tzdb zones it is generated from; run `cargo xtask tzdb` (T-41 rule 4, CM-64)".to_owned(),
        }]
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default()
    }

    #[test]
    fn the_vendored_zones_render_their_release_and_share_identical_files() {
        let text = render(&root()).unwrap();
        assert!(text.contains("pub(crate) const VERSION: &str = \"2026f\";"));
        assert!(text.contains(
            "(\"Asia/Istanbul\", include_bytes!(\"../../../../../conformance/tzdb/zoneinfo/Asia/Istanbul.tzif\")),"
        ));
        assert!(text.contains(
            "(\"Europe/Istanbul\", include_bytes!(\"../../../../../conformance/tzdb/zoneinfo/Asia/Istanbul.tzif\")),"
        ));
    }
}
