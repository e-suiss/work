//! ISO 4217 List One (CM-62): `cargo xtask iso4217` writes `crates/kernel/src/currency/list_one.rs` from SIX's List One vendored in `conformance/iso4217/list-one.xml`, and the `generated` check regenerates it and compares byte for byte.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::Violation;

/// The vendored List One.
pub(crate) const XML: &str = "conformance/iso4217/list-one.xml";

/// The generated kernel table.
pub(crate) const OUT: &str = "crates/kernel/src/currency/list_one.rs";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Entry {
    numeric: u16,
    minor_units: Option<u8>,
    fund: bool,
}

fn between<'a>(text: &'a str, open: &str, close: &str) -> Option<&'a str> {
    let start = text.find(open)?.checked_add(open.len())?;
    let rest = text.get(start..)?;
    rest.get(..rest.find(close)?)
}

fn entry(chunk: &str) -> Result<Option<(String, Entry)>, String> {
    let Some(code) = between(chunk, "<Ccy>", "</Ccy>") else {
        return Ok(None);
    };
    if code.len() != 3 || !code.bytes().all(|b| b.is_ascii_uppercase()) {
        return Err(format!("alphabetic code {code:?}"));
    }
    let numeric = between(chunk, "<CcyNbr>", "</CcyNbr>")
        .and_then(|n| n.parse::<u16>().ok())
        .ok_or_else(|| format!("{code}: numeric code"))?;
    let minor_units = match between(chunk, "<CcyMnrUnts>", "</CcyMnrUnts>") {
        Some("N.A.") => None,
        Some(n) => Some(
            n.parse::<u8>()
                .map_err(|_| format!("{code}: minor unit {n:?}"))?,
        ),
        None => return Err(format!("{code}: no minor unit element")),
    };
    let fund = chunk.contains("IsFund=\"true\"");
    Ok(Some((
        code.to_owned(),
        Entry {
            numeric,
            minor_units,
            fund,
        },
    )))
}

/// The kernel table for the List One text `xml`.
pub(crate) fn render(xml: &str) -> Result<String, String> {
    let published = between(xml, "Pblshd=\"", "\"").ok_or("no publication date")?;
    let mut entries: BTreeMap<String, Entry> = BTreeMap::new();
    for chunk in xml.split("<CcyNtry>").skip(1) {
        let chunk = chunk.split("</CcyNtry>").next().unwrap_or_default();
        if let Some((code, e)) = entry(chunk)? {
            if entries.get(&code).is_some_and(|have| *have != e) {
                return Err(format!("{code}: entries disagree"));
            }
            entries.insert(code, e);
        }
    }
    if entries.is_empty() {
        return Err("no entries".to_owned());
    }
    let mut out = format!(
        "//! ISO 4217 List One as SIX published it on {published}, generated by `cargo xtask iso4217` from `{XML}` (CM-62).\n\nuse super::Currency;\n\n/// The publication date of the vendored list.\npub(crate) const PUBLISHED: &str = \"{published}\";\n\n/// Every alphabetic code of the list once, in ascending order.\n#[rustfmt::skip]\npub(crate) const ENTRIES: &[Currency] = &[\n"
    );
    for (code, e) in &entries {
        let minor = e
            .minor_units
            .map_or_else(|| "None".to_owned(), |m| format!("Some({m})"));
        let _ = writeln!(
            out,
            "    Currency::new(\"{code}\", {}, {minor}, {}),",
            e.numeric, e.fund
        );
    }
    out.push_str("];\n");
    Ok(out)
}

fn read(root: &Path) -> Result<String, String> {
    let path = root.join(XML);
    std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))
}

/// `cargo xtask iso4217`: writes the kernel table.
pub(crate) fn write(root: &Path) -> Result<(), String> {
    let text = render(&read(root)?)?;
    let path = root.join(OUT);
    std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// The committed kernel table when it differs from a fresh generation (T-41 rule 4).
pub(crate) fn check(root: &Path) -> Result<Vec<Violation>, String> {
    let want = render(&read(root)?)?;
    let have = std::fs::read_to_string(root.join(OUT)).unwrap_or_default();
    Ok(if have == want {
        Vec::new()
    } else {
        vec![Violation {
            rule: "generated",
            path: PathBuf::from(OUT),
            message: "differs from the List One it is generated from; run `cargo xtask iso4217` (T-41 rule 4, CM-62)".to_owned(),
        }]
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "<ISO_4217 Pblshd=\"2026-01-01\">\r\n<CcyTbl>\r\n<CcyNtry><CtryNm>A</CtryNm><CcyNm>Euro</CcyNm><Ccy>EUR</Ccy><CcyNbr>978</CcyNbr><CcyMnrUnts>2</CcyMnrUnts></CcyNtry>\r\n<CcyNtry><CtryNm>B</CtryNm><CcyNm>Euro</CcyNm><Ccy>EUR</Ccy><CcyNbr>978</CcyNbr><CcyMnrUnts>2</CcyMnrUnts></CcyNtry>\r\n<CcyNtry><CtryNm>C</CtryNm><CcyNm>Gold</CcyNm><Ccy>XAU</Ccy><CcyNbr>959</CcyNbr><CcyMnrUnts>N.A.</CcyMnrUnts></CcyNtry>\r\n<CcyNtry><CtryNm>D</CtryNm><CcyNm IsFund=\"true\">Mvdol</CcyNm><Ccy>BOV</Ccy><CcyNbr>984</CcyNbr><CcyMnrUnts>2</CcyMnrUnts></CcyNtry>\r\n<CcyNtry><CtryNm>E</CtryNm><CcyNm>No universal currency</CcyNm></CcyNtry>\r\n</CcyTbl></ISO_4217>";

    #[test]
    fn list_one_codes_appear_once_in_order_with_funds_and_missing_minor_units() {
        let text = render(SAMPLE).unwrap();
        assert!(text.contains("pub(crate) const PUBLISHED: &str = \"2026-01-01\";"));
        let rows: Vec<&str> = text
            .lines()
            .filter(|l| l.contains("Currency::new"))
            .collect();
        assert_eq!(
            rows,
            [
                "    Currency::new(\"BOV\", 984, Some(2), true),",
                "    Currency::new(\"EUR\", 978, Some(2), false),",
                "    Currency::new(\"XAU\", 959, None, false),",
            ]
        );
    }

    #[test]
    fn list_one_entries_that_disagree_are_refused() {
        let bad = SAMPLE.replacen("<CcyNbr>978</CcyNbr>", "<CcyNbr>979</CcyNbr>", 1);
        assert!(render(&bad).is_err());
    }
}
